#!/usr/bin/env node
/** Derive every OD icon from the exact website logo; never redraw the mark.
 * Run: npm run brand:sync, or npm run brand:check to detect stale assets.
 */
import { readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const root = new URL("../", import.meta.url);
const source = await readFile(new URL("public/design/od-logo.png", root));
const revision = createHash("sha256").update(source).digest("hex").slice(0, 12);
const check = process.argv.includes("--check");
const outputs = new Map();
const png = (size) => sharp(source).resize(size, size, { fit: "contain" }).flatten({ background: "#007F70" }).png().toBuffer();
for (const [path, size] of [
  ["public/logo.png", 512],
  ["public/favicon.png", 96],
  ["public/favicon-48x48.png", 48],
  ["public/favicon-96x96.png", 96],
  ["public/apple-touch-icon.png", 180],
  ["public/icon-192.png", 192],
  ["public/icon-512.png", 512],
  ["app/icon.png", 96],
  ["mobile/assets/images/icon.png", 1024],
  ["mobile/assets/images/splash-icon.png", 512],
]) outputs.set(path, await png(size));
outputs.set("mobile/assets/brand/od.png", source);
// Keep the artwork inside Android's safe zone. Extend the original edge
// pixels so the gradient stays continuous instead of becoming a floating tile.
outputs.set("mobile/assets/images/adaptive-icon.png", await sharp(source)
  .resize(640, 640)
  .extend({ top: 192, bottom: 192, left: 192, right: 192, extendWith: "copy" })
  .flatten({ background: "#007F70" }).png().toBuffer());
// ICO directory with PNG frames for modern browsers and Windows at each size.
const sizes = [16, 32, 48];
const frames = await Promise.all(sizes.map(png));
const directory = Buffer.alloc(6 + 16 * frames.length);
directory.writeUInt16LE(1, 2);
directory.writeUInt16LE(frames.length, 4);
let offset = directory.length;
for (const [index, frame] of frames.entries()) {
  const entry = 6 + 16 * index;
  directory[entry] = sizes[index]; directory[entry + 1] = sizes[index];
  directory.writeUInt16LE(1, entry + 4); directory.writeUInt16LE(32, entry + 6);
  directory.writeUInt32LE(frame.length, entry + 8); directory.writeUInt32LE(offset, entry + 12);
  offset += frame.length;
}
outputs.set("public/favicon.ico", Buffer.concat([directory, ...frames]));
outputs.set("lib/brand-assets.ts", Buffer.from(`/** Generated by scripts/sync-brand-assets.mjs from the website logo. */\nexport const BRAND_ASSET_REVISION = "${revision}";\nexport const brandAssetUrl = (path: string) => \`\${path}?v=\${BRAND_ASSET_REVISION}\`;\n`));
const stale = [];
for (const [path, expected] of outputs) {
  const target = new URL(path, root);
  if (check) {
    const actual = await readFile(target).catch(() => null);
    if (!actual?.equals(expected)) stale.push(path);
  } else await writeFile(target, expected);
}
if (stale.length) throw new Error(`Stale brand assets: ${stale.join(", ")}. Run npm run brand:sync.`);
console.log(`${check ? "Verified" : "Updated"} ${outputs.size} brand assets from ${fileURLToPath(new URL("public/design/od-logo.png", root))} (${revision}).`);
