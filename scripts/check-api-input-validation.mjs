#!/usr/bin/env node

import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { cliLog } from "./lib/cli-logger.mjs";

const API_ROOT = "app/api";
const METHODS = ["GET", "POST", "PUT", "PATCH", "DELETE"];
const METHOD_EXPORT = new RegExp(
  `export\\s+(?:async\\s+)?function\\s+(${METHODS.join("|")})\\b`,
  "g",
);
const BODY_INPUT = /await\s+[A-Za-z_$][\w$]*\.(?:json|formData)\s*\(/;
const QUERY_INPUT = /(?:nextUrl|new\s+URL\([^)]*\))\.searchParams|\.searchParams\.(?:get|getAll|has)\s*\(/;
const PARAM_INPUT = /await\s+(?:[A-Za-z_$][\w$]*\.)?params\b/;
const ZOD_VALIDATION = /\.safeParse\s*\(|\.parse\s*\(/;

function routeFiles(directory) {
  return readdirSync(directory, { withFileTypes: true })
    .flatMap((entry) => {
      const path = join(directory, entry.name);
      if (entry.isDirectory()) return routeFiles(path);
      return entry.name === "route.ts" ? [path] : [];
    })
    .sort();
}

function methodBlocks(source) {
  const matches = [...source.matchAll(METHOD_EXPORT)];
  return matches.map((match, index) => ({
    method: match[1],
    source: source.slice(match.index, matches[index + 1]?.index ?? source.length),
  }));
}

function inspectRoute(file) {
  const source = readFileSync(file, "utf8");
  const route = `/${relative(API_ROOT, file).replace(/\/route\.ts$/, "")}`;
  return methodBlocks(source).map(({ method, source: block }) => {
    const inputs = [
      BODY_INPUT.test(block) ? "body" : null,
      QUERY_INPUT.test(block) ? "query" : null,
      PARAM_INPUT.test(block) ? "params" : null,
    ].filter(Boolean);
    const validated = inputs.length === 0 ? "N-A" : ZOD_VALIDATION.test(block) ? "evet" : "hayır";
    return { file, route: `/api${route === "/" ? "" : route}`, method, inputs, validated };
  });
}

const files = routeFiles(API_ROOT);
const rows = files.flatMap(inspectRoute);
const offenders = rows.filter((row) => row.validated === "hayır");

if (process.argv.includes("--write-inventory")) {
  const lines = [
    "# API input validation inventory",
    "",
    "Generated by `npm run lint:api-validation -- --write-inventory`.",
    "",
    "| Route path | Method | Validation | Note |",
    "|---|---|---|---|",
    ...rows.map((row) =>
      `| \`${row.route}\` | ${row.method} | ${row.validated} | ${row.inputs.length ? `Zod: ${row.inputs.join(", ")}` : "Input okumuyor"} |`,
    ),
    "",
  ];
  writeFileSync("docs/api-input-validation.md", lines.join("\n"));
}

if (offenders.length > 0) {
  cliLog.error("Zod doğrulaması olmadan API input'u okuyan route metotları:\n");
  for (const row of offenders) {
    cliLog.error(`  ${row.file} (${row.method}: ${row.inputs.join(", ")})`);
  }
  cliLog.error("\nHer metotta okunan body/query/params değerini Zod safeParse/parse ile doğrulayın.");
  process.exit(1);
}

cliLog.info(`API input validation: temiz (${files.length} route, ${rows.length} metot).`);
