#!/usr/bin/env node
import ts from "typescript";
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";

const files = execFileSync("find", ["app/api", "-name", "route.ts", "-type", "f"], { encoding: "utf8" }).trim().split("\n").filter(Boolean).sort();

function propertyName(property) {
  return property.name && ts.isIdentifier(property.name) || property.name && ts.isStringLiteral(property.name) ? property.name.text : null;
}

function objectProperties(node) {
  if (!node || !ts.isObjectLiteralExpression(node)) return new Map();
  return new Map(node.properties.filter(ts.isPropertyAssignment).map((property) => [propertyName(property), property.initializer]).filter(([name]) => name));
}

function familyFor(body) {
  const props = objectProperties(body);
  const keys = [...props.keys()];
  const error = props.get("error");
  const errorKind = error && ts.isObjectLiteralExpression(error) ? "object" : "string";
  if (props.has("success") && props.has("error")) return `{success:false,error:${errorKind}}`;
  if (props.has("ok") && props.has("error")) return `{ok:false,error:${errorKind}}`;
  if (props.has("error")) return `{error:${errorKind}}`;
  if (props.has("message")) return `{message}`;
  if (props.has("errors")) return `{errors}`;
  return keys.length ? `{${keys.join(",")}}` : "non-object JSON";
}

function numbers(node) {
  const found = [];
  function visit(child) {
    if (ts.isNumericLiteral(child)) found.push(Number(child.text));
    ts.forEachChild(child, visit);
  }
  if (node) visit(node);
  return found;
}

const inventory = files.map((file) => {
  const sourceText = readFileSync(file, "utf8");
  const source = ts.createSourceFile(file, sourceText, ts.ScriptTarget.Latest, true, ts.ScriptKind.TS);
  const statuses = new Set();
  const families = new Set();
  const examples = [];
  function visit(node) {
    if (ts.isCallExpression(node) && ts.isIdentifier(node.expression) && node.expression.text === "apiError") {
      numbers(node.arguments[0]).filter((status) => status >= 400).forEach((status) => statuses.add(status));
      families.add("{success:false,error:object}");
      if (examples.length < 2) examples.push(`apiError(${node.arguments.slice(0, 3).map((arg) => arg.getText(source)).join(", ")})`.slice(0, 110));
    }
    if (ts.isCallExpression(node) && ts.isPropertyAccessExpression(node.expression) && node.expression.name.text === "json") {
      const init = objectProperties(node.arguments[1]);
      const explicitStatuses = numbers(init.get("status"));
      const props = objectProperties(node.arguments[0]);
      const looksError = ["error", "errors", "message"].some((key) => props.has(key)) ||
        ((props.has("ok") || props.has("success")) && node.arguments[0].getText(source).includes("false"));
      if (looksError || explicitStatuses.some((status) => status >= 400)) {
        explicitStatuses.filter((status) => status >= 400).forEach((status) => statuses.add(status));
        families.add(familyFor(node.arguments[0]));
        if (examples.length < 2) examples.push(node.arguments[0].getText(source).replace(/\s+/g, " ").slice(0, 110));
      }
    }
    ts.forEachChild(node, visit);
  }
  visit(source);
  if (/\.response\b/.test(sourceText)) families.add("guard/auth passthrough");
  if (!families.size) families.add("no local JSON error");
  return { route: `/${file.replace(/^app\//, "").replace(/\/route\.ts$/, "")}`, statuses: [...statuses].sort((a, b) => a - b), families: [...families], examples };
});

const familyCounts = new Map();
for (const row of inventory) for (const family of row.families) familyCounts.set(family, (familyCounts.get(family) ?? 0) + 1);

const escape = (value) => value.replace(/\|/g, "\\|").replace(/`/g, "\\`");
const lines = [
  "# API error inventory",
  "",
  `Generated by \`node scripts/report-api-error-inventory.mjs --write\`. ${inventory.length} route dosyası statik olarak tarandı.`,
  "Dinamik guard/auth yanıtları ve helper içinde üretilen gövdeler ayrıca `guard/auth passthrough` olarak işaretlenir; bu envanter runtime trafiği değil kaynak kodu ölçer.",
  "",
  "## Shape families",
  "",
  "| Family | Route count |",
  "| --- | ---: |",
  ...[...familyCounts].sort((a, b) => b[1] - a[1]).map(([family, count]) => `| \`${escape(family)}\` | ${count} |`),
  "",
  "## Route inventory",
  "",
  "| Route | Explicit error statuses | Error body families | Example |",
  "| --- | --- | --- | --- |",
  ...inventory.map((row) => `| \`${row.route}\` | ${row.statuses.join(", ") || "—"} | ${row.families.map((family) => `\`${escape(family)}\``).join("<br>")} | ${escape(row.examples[0] ?? "—")} |`),
  "",
];
const output = lines.join("\n");
if (process.argv.includes("--write")) {
  writeFileSync("docs/api-error-inventory.md", output);
  process.stdout.write(`docs/api-error-inventory.md yazıldı (${inventory.length} route, ${familyCounts.size} aile).\n`);
} else {
  process.stdout.write(output);
}
