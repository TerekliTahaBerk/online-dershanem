import { test, expect } from '@playwright/test';
import { PrismaClient } from '@prisma/client';
import { createHash, randomBytes, randomUUID } from 'node:crypto';
import { parseEducationEditor } from '../../lib/mobile-contracts/admin-education-editor';

test('P3 teacher parity: templates, outcomes, education writes, review, analysis and mock exams', async ({ request }) => {
  test.skip(!process.env.DATABASE_URL, 'Isolated DB required');
  const db = new PrismaClient();
  const users: string[] = [], groups: string[] = [];
  const run = randomUUID();
  async function teacher() {
    const user = await db.user.create({ data: { email: `teacher-${users.length}-${run}@example.com`, role: 'TEACHER', status: 'ACTIVE', mustChangePassword: false, passwordHash: 'unused', inviteAcceptedAt: new Date() } });
    users.push(user.id);
    const token = randomBytes(32).toString('base64url');
    await db.session.create({ data: { userId: user.id, tokenHash: createHash('sha256').update(token).digest('hex'), expiresAt: new Date(Date.now() + 3_600_000), mfaVerifiedAt: new Date() } });
    return { user, headers: { authorization: `Bearer ${token}`, 'x-od-client': 'mobile', 'x-od-client-version': '1.0.0' } };
  }
  try {
    const owner = await teacher(), foreign = await teacher();
    const group = await db.group.create({ data: { name: 'Own group', subject: 'Matematik', teacherId: owner.user.id } });
    const other = await db.group.create({ data: { name: 'Foreign group', subject: 'Matematik', teacherId: foreign.user.id } });
    groups.push(group.id, other.id);
    const lesson = await db.lesson.create({ data: { groupId: group.id, teacherId: owner.user.id, title: 'Linked lesson', startsAt: new Date(), endsAt: new Date(Date.now() + 3_600_000) } });
    const templateHeaders = { ...owner.headers, 'X-Od-Idempotency-Key': randomUUID() };
    const templateBody = { title: 'Native template', note: 'Ortak özet', nextGoal: 'Sonraki adım', homework: 'Çalışma' };
    const templateResponse = await request.post('/api/panel/teacher/templates', { headers: templateHeaders, data: templateBody });
    expect(templateResponse.status(), await templateResponse.text()).toBe(200);
    const template = await templateResponse.json();
    expect((await request.post('/api/panel/teacher/templates', { headers: templateHeaders, data: templateBody })).status()).toBe(200);
    expect(await db.teacherNoteTemplate.count({ where: { teacherId: owner.user.id } })).toBe(1);
    expect((await request.post('/api/panel/teacher/templates', { headers: templateHeaders, data: { ...templateBody, title: 'Changed' } })).status()).toBe(409);
    const teacherDetail = await request.get(`/api/panel/staff/teacher/lessons/${lesson.id}`, { headers: owner.headers });
    expect(teacherDetail.status(), await teacherDetail.text()).toBe(200);
    expect((await teacherDetail.json()).noteTemplates[0].revision).toBe(template.revision);
    const templatePath = `/api/panel/teacher/templates/${template.id}`;
    const templateControl = { 'X-Od-Idempotency-Key': randomUUID(), 'X-Od-Expected-Revision': template.revision };
    expect((await request.patch(templatePath, { headers: { ...foreign.headers, ...templateControl }, data: templateBody })).status()).toBe(404);
    const updatedTemplate = await request.patch(templatePath, { headers: { ...owner.headers, ...templateControl }, data: { ...templateBody, note: 'Updated' } });
    expect(updatedTemplate.status(), await updatedTemplate.text()).toBe(200);
    expect((await request.patch(templatePath, { headers: { ...owner.headers, ...templateControl, 'X-Od-Idempotency-Key': randomUUID() }, data: templateBody })).status()).toBe(409);
    const deleteHeaders = { ...owner.headers, 'X-Od-Idempotency-Key': randomUUID(), 'X-Od-Expected-Revision': (await updatedTemplate.json()).revision };
    expect((await request.delete(templatePath, { headers: deleteHeaders })).status()).toBe(200);
    expect((await request.delete(templatePath, { headers: deleteHeaders })).status()).toBe(200);
    await db.teacherNoteTemplate.createMany({ data: Array.from({ length: 19 }, (_, index) => ({ teacherId: owner.user.id, title: `Saved ${index}` })) });
    const capResponses = await Promise.all(Array.from({ length: 2 }, () => request.post('/api/panel/teacher/templates', { headers: { ...owner.headers, 'X-Od-Idempotency-Key': randomUUID() }, data: templateBody })));
    expect(capResponses.filter((response) => response.status() === 200)).toHaveLength(1);
    expect(capResponses.filter((response) => [400, 409].includes(response.status()))).toHaveLength(1);
    expect(await db.teacherNoteTemplate.count({ where: { teacherId: owner.user.id } })).toBe(20);
    const curriculum = await db.curriculumVersion.create({ data: { code: `native-${run}`, title: 'Native catalog', academicYear: 2026, status: 'ACTIVE', createdById: owner.user.id, subjects: { create: { code: 'MAT', name: 'Matematik', units: { create: { code: 'U1', name: 'Ünite', outcomes: { create: { code: run, title: 'Native kazanım' } } } } } } }, include: { subjects: { include: { units: { include: { outcomes: true } } } } } });
    const outcome = curriculum.subjects[0].units[0].outcomes[0];
    const searchPath = `/api/panel/curriculum/outcomes/search?lessonId=${lesson.id}&query=${run}`;
    expect((await request.get(searchPath, { headers: foreign.headers })).status()).toBe(404);
    const search = await request.get(searchPath, { headers: owner.headers });
    expect(search.status(), await search.text()).toBe(200);
    expect((await search.json()).outcomes[0].favorite).toBe(false);
    const favorite = () => request.post('/api/panel/teacher/outcome-favorites', { headers: owner.headers, data: { outcomeId: outcome.id, favorite: true } });
    expect((await favorite()).status()).toBe(200); expect((await favorite()).status()).toBe(200);
    expect(await db.outcomeFavorite.count({ where: { userId: owner.user.id, outcomeId: outcome.id } })).toBe(1);
    expect((await (await request.get(searchPath, { headers: owner.headers })).json()).outcomes[0].favorite).toBe(true);
    const read = (query: string, headers = owner.headers) => request.get(`/api/panel/staff/teacher/education?${query}`, { headers });
    const response = await read(`kind=assignment&lesson=${lesson.id}`);
    expect(response.status(), await response.text()).toBe(200);
    expect(response.headers()['cache-control']).toContain('no-store');
    const parsed = parseEducationEditor(await response.json());
    expect(parsed.ok).toBe(true);
    if (!parsed.ok) throw new Error(parsed.error);
    const form = parsed.value.forms[0];
    const groupField = form.fields.find((field) => field.key === 'groupId')!;
    expect(groupField.options.map((option) => option.id)).toEqual([group.id]);
    expect(groupField.value).toBe(group.id);
    expect(form.fields.find((field) => field.key === 'lessonId')!.value).toBe(lesson.id);
    expect((await read(`kind=assignment&group=${other.id}`)).status()).toBe(404);
    expect((await read(`kind=assignment&lesson=${lesson.id}`, foreign.headers)).status()).toBe(404);
    expect((await read('kind=setup')).status()).toBe(400);
    const key = randomUUID();
    const headers = { ...owner.headers, 'X-Od-Idempotency-Key': key, 'X-Od-Expected-Revision': groupField.options[0].revision! };
    const body = { groupId: group.id, lessonId: lesson.id, title: 'Native teacher homework', description: 'Details', dueAt: new Date(Date.now() + 86_400_000).toISOString(), outcomeSkipReason: 'COMPLETE_LATER' };
    const created = await request.post('/api/panel/assignments', { headers, data: body });
    expect(created.status(), await created.text()).toBe(200);
    const assignment = await created.json();
    const replay = await request.post('/api/panel/assignments', { headers, data: body });
    expect((await replay.json()).replayed).toBe(true);
    expect(await db.assignment.count({ where: { groupId: group.id } })).toBe(1);
    expect((await request.post('/api/panel/assignments', { headers, data: { ...body, title: 'Different payload' } })).status()).toBe(409);
    expect((await request.post('/api/panel/assignments', { headers: owner.headers, data: body })).status()).toBe(400);
    const detail = await read(`kind=assignment&id=${assignment.id}`);
    const edit = (await detail.json()).forms[0];
    const updateBody = { title: 'Updated homework', description: 'New', dueAt: body.dueAt, isActive: true, outcomeIds: [], outcomeSkipReason: 'COMPLETE_LATER' };
    const updateHeaders = { ...owner.headers, 'X-Od-Idempotency-Key': randomUUID(), 'X-Od-Expected-Revision': edit.revision };
    expect((await request.patch(`/api/panel/assignments/${assignment.id}`, { headers: updateHeaders, data: updateBody })).status()).toBe(200);
    expect((await request.patch(`/api/panel/assignments/${assignment.id}`, { headers: { ...updateHeaders, 'X-Od-Idempotency-Key': randomUUID() }, data: updateBody })).status()).toBe(409);
    expect((await read(`kind=assignment&id=${assignment.id}`, foreign.headers)).status()).toBe(404);
    const materialResponse = await read(`kind=material&group=${group.id}`);
    const materialForm = (await materialResponse.json()).forms.find((item: { id: string }) => item.id === 'LINK');
    const materialGroup = materialForm.fields.find((field: { key: string }) => field.key === 'groupId');
    const material = await request.post('/api/panel/materials', { headers: { ...owner.headers, 'X-Od-Idempotency-Key': randomUUID(), 'X-Od-Expected-Revision': materialGroup.options[0].revision }, data: { groupId: group.id, title: 'Native material', url: 'https://example.com/source', kind: 'LINK' } });
    expect(material.status(), await material.text()).toBe(200);
    const materialId = (await material.json()).material.id;
    expect((await read(`kind=material&id=${materialId}`, foreign.headers)).status()).toBe(404);
    const materialDetail = await read(`kind=material&id=${materialId}`);
    expect(materialDetail.status(), await materialDetail.text()).toBe(200);
    const materialRevision = (await materialDetail.json()).forms[0].revision;
    const materialEditBody = { title: 'Updated material', description: 'New', url: 'https://example.com/new', isActive: true };
    const materialEditHeaders = { ...owner.headers, 'X-Od-Idempotency-Key': randomUUID(), 'X-Od-Expected-Revision': materialRevision };
    expect((await request.patch(`/api/panel/materials/${materialId}`, { headers: { ...materialEditHeaders, ...foreign.headers }, data: materialEditBody })).status()).toBe(404);
    const materialEdit = await request.patch(`/api/panel/materials/${materialId}`, { headers: materialEditHeaders, data: materialEditBody });
    expect(materialEdit.status(), await materialEdit.text()).toBe(200);
    expect((await request.patch(`/api/panel/materials/${materialId}`, { headers: { ...materialEditHeaders, 'X-Od-Idempotency-Key': randomUUID() }, data: materialEditBody })).status()).toBe(409);
    const upload = await request.post('/api/panel/materials/upload', { headers: { ...owner.headers, 'X-Od-Idempotency-Key': randomUUID(), 'X-Od-Expected-Revision': materialGroup.options[0].revision }, multipart: { groupId: group.id, title: 'Invalid upload', file: { name: 'large.pdf', mimeType: 'application/pdf', buffer: Buffer.alloc(4 * 1024 * 1024 + 1) } } });
    expect(upload.status()).toBe(413);
    const learner = await db.user.create({ data: { email: `learner-${run}@example.com`, role: 'STUDENT', status: 'ACTIVE', passwordHash: 'unused' } });
    users.push(learner.id);
    const profile = await db.studentProfile.create({ data: { userId: learner.id } });
    const enrollment = await db.enrollment.create({ data: { groupId: group.id, studentId: profile.id } });
    const reviewResponse = await request.get('/api/panel/staff/teacher/review', { headers: owner.headers });
    expect(reviewResponse.status(), await reviewResponse.text()).toBe(200);
    const reviewStudent = (await reviewResponse.json()).students[0];
    expect(reviewStudent.id).toBe(profile.id);
    const reviewHeaders = { ...owner.headers, 'X-Od-Idempotency-Key': randomUUID(), 'X-Od-Expected-Revision': reviewStudent.revision };
    const reviewBody = { studentId: profile.id, title: 'Kaynak tekrarı', sourceReference: 'Föy 2, soru 3' };
    const createReview = () => request.post('/api/panel/review-queue', { headers: reviewHeaders, data: reviewBody });
    const reviewCreated = await createReview();
    expect(reviewCreated.status(), await reviewCreated.text()).toBe(200);
    expect((await (await createReview()).json()).replayed).toBe(true);
    expect(await db.reviewItem.count({ where: { studentId: profile.id } })).toBe(1);
    expect((await request.post('/api/panel/review-queue', { headers: { ...foreign.headers, 'X-Od-Idempotency-Key': randomUUID(), 'X-Od-Expected-Revision': reviewStudent.revision }, data: reviewBody })).status()).toBe(404);
    expect((await request.post('/api/panel/review-queue', { headers: { ...reviewHeaders, 'X-Od-Idempotency-Key': randomUUID(), 'X-Od-Expected-Revision': '0'.repeat(64) }, data: reviewBody })).status()).toBe(409);
    const analysisResponse = await request.get('/api/panel/staff/teacher/analysis', { headers: owner.headers });
    expect(analysisResponse.status(), await analysisResponse.text()).toBe(200);
    expect(analysisResponse.headers()['cache-control']).toContain('no-store');
    const analysis = await analysisResponse.json();
    expect(analysis.rows.map((row: { studentId: string }) => row.studentId)).toEqual([profile.id]);
    const foreignAnalysis = await request.get('/api/panel/staff/teacher/analysis', { headers: foreign.headers });
    expect((await foreignAnalysis.json()).rows).toEqual([]);
    const examBody = { studentId: profile.id, exam: 'YDT', takenAt: new Date().toISOString(), sections: [{ subjectCode: 'YDT', correctCount: 70, incorrectCount: 8, blankCount: 2, errorCategories: ['TIME'] }], idempotencyKey: randomUUID() };
    const examResponse = await request.post('/api/panel/mock-exams', { headers: owner.headers, data: examBody });
    expect(examResponse.status(), await examResponse.text()).toBe(200);
    const examsPath = `/api/panel/staff/teacher/mock-exams?ogrenci=${profile.id}`;
    const exams = await request.get(examsPath, { headers: owner.headers });
    expect(exams.status(), await exams.text()).toBe(200);
    expect(exams.headers()['cache-control']).toContain('no-store');
    const workspace = await exams.json();
    expect(workspace.students.map((item: { id: string }) => item.id)).toEqual([profile.id]);
    expect((await request.get(examsPath, { headers: foreign.headers })).status()).toBe(404);
    expect((await request.post('/api/panel/mock-exams', { headers: foreign.headers, data: { ...examBody, idempotencyKey: randomUUID() } })).status()).toBe(404);
    const exam = workspace.exams[0];
    const approved = await request.patch(`/api/panel/mock-exams/${exam.id}`, { headers: owner.headers, data: { reasons: exam.sections.map((section: { id: string }) => ({ sectionId: section.id, categories: ['TIME'] })), nextAction: 'Kısa süreli prova', expectedRevision: exam.revision, idempotencyKey: randomUUID() } });
    expect(approved.status(), await approved.text()).toBe(204);
    await db.enrollment.update({ where: { id: enrollment.id }, data: { endedAt: new Date() } });
    expect((await request.get(examsPath, { headers: owner.headers })).status()).toBe(404);
    expect((await (await request.get('/api/panel/staff/teacher/analysis', { headers: owner.headers })).json()).rows).toEqual([]);
  } finally {
    await db.reviewItem.deleteMany({ where: { createdById: { in: users } } });
    await db.notification.deleteMany({ where: { userId: { in: users } } });
    await db.learningMaterial.deleteMany({ where: { groupId: { in: groups } } });
    await db.assignment.deleteMany({ where: { groupId: { in: groups } } });
    await db.lesson.deleteMany({ where: { groupId: { in: groups } } });
    await db.group.deleteMany({ where: { id: { in: groups } } });
    await db.mockExam.deleteMany({ where: { student: { userId: { in: users } } } });
    await db.studentProfile.deleteMany({ where: { userId: { in: users } } });
    await db.teacherNoteTemplate.deleteMany({ where: { teacherId: { in: users } } });
    await db.curriculumVersion.deleteMany({ where: { createdById: { in: users } } });
    await db.auditLog.deleteMany({ where: { actorUserId: { in: users } } });
    await db.session.deleteMany({ where: { userId: { in: users } } });
    await db.user.deleteMany({ where: { id: { in: users } } });
    await db.$disconnect();
  }
});
